function detect() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY)
    if (stored === 'en' || stored === 'de') return stored
  } catch { /* private mode */ }
  return (navigator.language || 'en').toLowerCase().startsWith('de') ? 'de' : 'en'
}

export const lang = detect()
/** Locale for dates and numbers; en-GB keeps the 24-hour clock. */
export const locale = lang === 'de' ? 'de-DE' : 'en-GB'

export function t(key, params = {}) {
  const value = STRINGS[lang][key] ?? STRINGS.en[key] ?? key
  return typeof value === 'function' ? value(params) : value
}

export function setLang(value) {
  try { localStorage.setItem(STORAGE_KEY, value) } catch { /* private mode */ }
  location.reload()
}

/** Applies data-i18n (text), data-i18n-html (trusted markup from this file) and attribute variants. */
export function translatePage(root = document) {
  document.documentElement.lang = lang
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n)
  for (const node of root.querySelectorAll('[data-i18n-html]')) node.innerHTML = t(node.dataset.i18nHtml)
  for (const [attr, data] of [['placeholder', 'i18nPlaceholder'], ['aria-label', 'i18nAriaLabel'], ['title', 'i18nTitle'], ['value', 'i18nValue']]) {
    for (const node of root.querySelectorAll(`[data-${data.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())}]`)) node.setAttribute(attr, t(node.dataset[data]))
  }
}

